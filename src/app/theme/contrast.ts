/**
 * WCAG 2.1 relative luminance and contrast ratio.
 *
 * This exists so the palette is measured rather than asserted. Both palette
 * bugs recorded in the spec — an amber sitting exactly on the 4.5:1 threshold,
 * and a surface separated from its ground by 1.08:1 — were invisible to
 * inspection and obvious to arithmetic.
 */

function channel(value: number): number {
  const c = value / 255
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

export function relativeLuminance(hex: string): number {
  const h = hex.replace('#', '')
  const r = parseInt(h.slice(0, 2), 16)
  const g = parseInt(h.slice(2, 4), 16)
  const b = parseInt(h.slice(4, 6), 16)
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)
}

export function contrastRatio(a: string, b: string): number {
  const la = relativeLuminance(a)
  const lb = relativeLuminance(b)
  const hi = Math.max(la, lb)
  const lo = Math.min(la, lb)
  return (hi + 0.05) / (lo + 0.05)
}
